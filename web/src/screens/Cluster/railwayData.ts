export const RAILWAY_ZONES: string[] = Object.keys(RAILWAY_DATA);

export const divisionsForZone = (zone?: string | null): string[] => {
  if (!zone) return [];
  const normalized = zone.trim().toLowerCase().replace(/s$/, '');
  const key = Object.keys(RAILWAY_DATA).find((z) => {
    const normZ = z.toLowerCase().replace(/s$/, '');
    return normZ === normalized || normalized.includes(normZ) || normZ.includes(normalized);
  });
  return key ? RAILWAY_DATA[key] : [];
};

export const stationsForDivision = (division?: string | null): StationReference[] => {
  if (!division) return [];
  const key = Object.keys(RAILWAY_STATIONS).find(
    (d) => d.toLowerCase() === division.trim().toLowerCase()
  );
  if (key) return RAILWAY_STATIONS[key];
  return [
    { code: `${division.substring(0, 3).toUpperCase()}-01`, name: `${division} Main Station` },
    { code: `${division.substring(0, 3).toUpperCase()}-02`, name: `${division} Junction` },
  ];
};
